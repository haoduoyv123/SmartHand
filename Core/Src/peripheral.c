/**
  * @brief printf 重定向：newlib 的 _write 最终调用 __io_putchar
  *        工程已使用 nano.specs，printf 输出经 syscalls.c 的 _write -> __io_putchar
  */
int __io_putchar(int ch)
{
  uint8_t c = (uint8_t)ch;
  HAL_UART_Transmit(&huart1, &c, 1, HAL_MAX_DELAY);
  return ch;
}

